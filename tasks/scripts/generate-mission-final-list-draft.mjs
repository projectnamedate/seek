const expected = {
  outdoor: { t1: 14, t2: 12, t3: 10 },
  indoor: { t1: 6, t2: 8, t3: 10 },
};

function idFor(tier, index) {
  return `t${tier}-${String(index + 1).padStart(3, '0')}`;
}

function titleForTier(tier) {
  if (tier === 1) return 'Tier 1 - Easy - 1000 SKR - 3 minutes';
  if (tier === 2) return 'Tier 2 - Medium - 3000 SKR - 2 minutes';
  return 'Tier 3 - Hard - 5000 SKR - 1 minute';
}

function missionLine(id, text) {
  return `- \`${id}\` Find ${text}`;
}

function validate() {
  for (const family of families) {
    const shape = expected[family.location];
    for (const tierKey of ['t1', 't2', 't3']) {
      if (family[tierKey].length !== shape[tierKey]) {
        throw new Error(`${family.name} ${tierKey} expected ${shape[tierKey]}, got ${family[tierKey].length}`);
      }
    }
  }
}

function rowsFor(tier, location) {
  const key = `t${tier}`;
  return families
    .filter((family) => family.location === location)
    .flatMap((family) => family[key].map((text) => ({ family: family.name, text })));
}

function renderTier(tier) {
  const outdoorRows = rowsFor(tier, outdoor);
  const indoorRows = rowsFor(tier, indoor);
  const lines = [`## ${titleForTier(tier)}`, ''];

  lines.push(`### Outdoor (${outdoorRows.length})`, '');
  let offset = 0;
  for (const family of families.filter((entry) => entry.location === outdoor)) {
    const tasks = family[`t${tier}`];
    lines.push(`#### ${family.name}`, '');
    for (const text of tasks) {
      lines.push(missionLine(idFor(tier, offset), text));
      offset += 1;
    }
    lines.push('');
  }

  lines.push(`### Indoor (${indoorRows.length})`, '');
  for (const family of families.filter((entry) => entry.location === indoor)) {
    const tasks = family[`t${tier}`];
    lines.push(`#### ${family.name}`, '');
    for (const text of tasks) {
      lines.push(missionLine(idFor(tier, offset), text));
      offset += 1;
    }
    lines.push('');
  }

  if (offset !== 200) {
    throw new Error(`tier ${tier} expected 200 missions, got ${offset}`);
  }

  return lines;
}

